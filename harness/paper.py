def _mpl():
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    plt.rcParams.update({"font.family": "sans-serif", "font.sans-serif": ["DejaVu Sans"], "font.size": 7,
                         "axes.labelsize": 7, "xtick.labelsize": 6.5, "ytick.labelsize": 7, "legend.fontsize": 6.5,
                         "axes.spines.top": False, "axes.spines.right": False, "axes.linewidth": 0.6,
                         "xtick.major.width": 0.6, "ytick.major.width": 0, "ytick.major.size": 0, "pdf.fonttype": 42})
    return plt


def _dot_panel(ax, rows, vals, unit, sign=None, xlabel="", models=MODELS):
    """rows: [(cid, label)]; one dot + 95% interval per model, offset vertically within each row."""
    sign = sign or {}
    n = len(models)
    for i, (cid, lab) in enumerate(rows):
        y0 = len(rows) - 1 - i
        for j, (mn, name, tag, col, mk) in enumerate(models):
            if mn not in vals.get(cid, {}):
                continue
            m, h, k, v = vals[cid][mn]
            s = sign.get(cid, 1)
            y = y0 + (n - 1) / 2 * 0.17 - j * 0.17
            ax.plot([s * m - (h or 0), s * m + (h or 0)], [y, y], color=col, lw=1.1, solid_capstyle="butt")
            ax.plot(s * m, y, mk, color=col, ms=4.2, mec=col, mfc=col if v in ("supported", "consistent") else "white",
                    mew=1.0, zorder=3)
    ax.axvline(0, color="0.55", lw=0.6, zorder=0)
    ax.set_yticks(range(len(rows)))
    ax.set_yticklabels([lab for _, lab in rows][::-1])
    ax.set_ylim(-0.6, len(rows) - 0.4)
    ax.set_xlabel(xlabel)
    ax.spines["left"].set_visible(False)


