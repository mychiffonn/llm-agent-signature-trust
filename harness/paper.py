def _write_all(files):
    """Write every output to a temp file first, then move them all into place, so a failure leaves no mixture."""
    tmp = []
    for path, content in files.items():
        os.makedirs(os.path.dirname(path), exist_ok=True)
        fd, t = tempfile.mkstemp(dir=os.path.dirname(path))
        with os.fdopen(fd, "w") as f:
            f.write(content)
        tmp.append((t, path))
    for t, path in tmp:
        os.replace(t, path)


