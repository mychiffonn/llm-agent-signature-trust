def macro_id(cid):
    digits = {"1": "One", "2": "Two", "3": "Three", "4": "Four"}
    s = "E" + digits[cid[1]] + cid[2].upper()
    return s + ("Prime" if cid.endswith("′") else "")


def tex_escape(s):
    rep = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_", "{": r"\{",
           "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}", "→": r"$\rightarrow$",
           "≈": r"$\approx$", "—": "---", "–": "--", "“": "``", "”": "''", "’": "'", "‘": "`", "…": r"\ldots{}"}
    out = "".join(rep.get(ch, ch) for ch in s)
    bad = [ch for ch in out if ord(ch) > 255]
    if bad:
        raise ValueError(f"unsupported characters in quote: {bad}")
    return out


# ------------------------------------------------------------------ data
def load():
    pk_sets = R.load_packets()
    by = defaultdict(list)
    for x in R.load_sweeps():
        if x["version"] == R.DESIGN_VERSION:
            by[x["meta"].get("model")].append(x)
    sw_sets = [R.merge_sweeps(v) for v in by.values()]
    conf = R.study_rows(pk_sets, sw_sets, True)
    return pk_sets, sw_sets, conf


def claim_values(conf):
    """{cid: {model: (mean, half-width, n, verdict word)}} and {cid: unit}"""
    vals, unit = {}, {}
    for spec, res in conf:
        cid = spec[0]
        unit[cid] = spec[4]
        vals[cid] = {mn: (m, h, n, v.split(" (")[0]) for mn, m, h, n, v in res if m is not None}
    return vals, unit


def fmt(x, unit, signed=True):
    return (f"{x:+.2f}" if signed else f"{x:.2f}") if unit == "reports" else (f"{x:+.0f}" if signed else f"{x:.0f}")


def fmt_tex(x, unit, signed=True):
    return fmt(x, unit, signed).replace("-", "$-$").replace("+", "$+$")


# ------------------------------------------------------------------ macros
class Macros:
    def __init__(self):
        self.d = {}

    def __setitem__(self, k, v):
        if not re.fullmatch(r"[A-Za-z]+", k):
            raise ValueError(f"bad macro name {k}")
        if k in self.d:
            raise ValueError(f"duplicate macro {k}")
        self.d[k] = v

    def tex(self):
        return "% generated by harness/paper.py from results/*; do not edit\n" + "".join(
            f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in sorted(self.d.items()))


def build_macros(pk_sets, sw_sets, vals, unit, cod):
    M = Macros()
    for cid, per in vals.items():
        mid = macro_id(cid)
        n_clear = 0
        for mn, (m, h, n, v) in per.items():
            if mn not in MID:
                raise ValueError(f"unknown model {mn}")
            tag = MID[mn][2]
            M[f"Val{mid}{tag}"] = fmt_tex(m, unit[cid])
            M[f"Abs{mid}{tag}"] = fmt(abs(m), unit[cid], signed=False)
            M[f"CI{mid}{tag}"] = fmt(h or 0, unit[cid], signed=False)
            n_clear += v in ("supported", "consistent")
        M[f"Tally{mid}"] = f"{n_clear} of {len(per)}"
    conf_rows = [r for d in pk_sets for r in d["sig_rows"] if r["config"]["seed"] >= R.CONFIRM_SEED0]
    pilot_rows = [r for d in pk_sets for r in d["sig_rows"] if r["config"]["seed"] < R.CONFIRM_SEED0]
    M["NConfTrials"] = f"{len(conf_rows):,}"
    M["NPilotTrials"] = f"{len(pilot_rows):,}"
    M["NModels"] = str(len({d["model"] for d in pk_sets if any(r["config"]["seed"] >= R.CONFIRM_SEED0 for r in d["sig_rows"])}))
    n_net = sum(1 for d in sw_sets for r in d["rows"] if r["config"]["seed"] >= R.CONFIRM_SEED0 and r["config"].get("badge"))
    M["NNetSims"] = str(n_net)
    M["NSeeds"] = str(len({r["config"]["seed"] for r in conf_rows}))
    M["NPilotSeeds"] = str(len({r["config"]["seed"] for r in pilot_rows}))
    # design constants, from the code that runs the experiments
    cfg = R.Config()
    words = {2: "two", 3: "three", 4: "four", 5: "five", 15: "15"}
    M["NWitnesses"], M["NWitnessesWord"] = str(cfg.n_observers), words[cfg.n_observers]
    M["NCorrect"], M["NWrong"] = str(cfg.n_correct), str(cfg.n_observers - cfg.n_correct)
    M["Reliability"] = f"{cfg.p:.2f}"
    M["NAgents"], M["NRounds"], M["WordLimit"] = str(cfg.n_agents), str(cfg.rounds), str(R.WORD_LIMIT)
    M["NDomains"] = str(len(R.DOMAINS))
    M["NetPuppets"], M["NetPuppetsFirst"] = str(R.FLOORFIX_NET["n_puppets"]), str(R.ORIG_NET["n_puppets"])
    M["RegistryCoveragePct"] = f"{100 * min(c[2] for c in CHECK_COLS):.0f}"
    M["ConfirmSeedZero"] = str(R.CONFIRM_SEED0)
    # transcript codings
    for key, per in cod.items():
        k = "".join(p.capitalize() for p in key.split("_"))
        for mn, (rate, n) in per.items():
            if rate is not None:
                M[f"Rate{k}{MID[mn][2]}"] = f"{100 * rate:.0f}"
                M[f"N{k}{MID[mn][2]}"] = str(n)
    # E1 example cell: no attack, reliability not stated, only one side signs
    for mn, name, tag, *_ in MODELS:
        d = next((d for d in pk_sets if d["model"] == mn), None)
        if not d:
            continue
        ix = R.conf_index([r for r in d["sig_rows"] if r["config"]["seed"] >= R.CONFIRM_SEED0])
        for sig, lab in (("truth", "TrueSigned"), ("false", "FalseSigned"), ("none", "NoneSigned")):
            for arm, alab in (("P2", ""), ("P2+attr", "Attr")):
                v = [r["p_truth"] for r in ix.get((False, arm, "none", sig, 1.0), {}).values()]
                if v:
                    M[f"PTruth{lab}{alab}{tag}"] = f"{st.fmean(v):.2f}"
    return M


# ------------------------------------------------------------------ tables
def claims_table(vals, unit):
    order = ["E1a", "E1b", "E1c", "E1d", "E2a", "E2b", "E3a", "E3b", "E3c", "E3d", "E4a", "E4b", "E4a′", "E4b′"]
    lines = ["\\begin{tabular}{@{}l l " + " ".join("c" for _ in MODELS) + "@{}}", "\\toprule",
             "Comparison & Unit & " + " & ".join(f"\\makecell{{{n.replace(' ', '\\\\', 1)}}}" for _, n, *_ in MODELS)
             + " \\\\", "\\midrule"]
    last_q = None
    for cid in order:
        if cid not in vals:
            raise ValueError(f"missing claim {cid}")
        q = cid[:2]
        if q != last_q:
            if last_q:
                lines.append("\\addlinespace")
            lines.append(f"\\multicolumn{{{2 + len(MODELS)}}}{{@{{}}l}}{{\\textit{{{QUESTION[q]}}}}} \\\\")
            last_q = q
        cells = []
        for mn, *_ in MODELS:
            if mn not in vals[cid]:
                cells.append("--")
                continue
            m, h, n, v = vals[cid][mn]
            s = f"{fmt_tex(m, unit[cid])} $\\pm$ {fmt(h or 0, unit[cid], False)}"
            cells.append(f"\\textbf{{{s}}}" if v in ("supported", "consistent") else s)
        u = "reports" if unit[cid] == "reports" else "BI"
        lines.append(f"{CLAIM_TEXT[cid]} & {u} & " + " & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    return "% generated by harness/paper.py; do not edit\n" + "\n".join(lines) + "\n"


CHECK_COLS = [("P0", "all", 1.0, "Plain"), ("P2U", "all", 1.0, "Unsigned"), ("P2", "all", 1.0, "Signed"),
              ("P3", "all", 1.0, "Count"), ("P3", "all", 0.6, "\\makecell{Count,\\\\60\\% reg.}"),
              ("P3", "none", 1.0, "\\makecell{Count,\\\\none sign}")]
CHECK_ROWS = [("none", "No attack"), ("sock3", "3 fake witnesses"), ("echo3", "1 fake, 3 relayers"),
              ("forged", "Forgery"), ("captured", "Captured witness")]


def checks_table(pk_sets):
    lines = ["\\begin{tabular}{@{}l l " + " ".join("r" for _ in CHECK_COLS) + "@{}}", "\\toprule",
             "Model & Attack & " + " & ".join(c[3] for c in CHECK_COLS) + " \\\\", "\\midrule"]
    first = True
    for mn, name, *_ in MODELS:
        d = next((d for d in pk_sets if d["model"] == mn), None)
        if not d:
            raise ValueError(f"no data for {mn}")
        ix = R.conf_index([r for r in d["sig_rows"] if r["config"]["seed"] >= R.CONFIRM_SEED0])
        if not first:
            lines.append("\\addlinespace")
        first = False
        for i, (pkt, lab) in enumerate(CHECK_ROWS):
            cells = []
            for arm, sig, cov, _ in CHECK_COLS:
                v = [r["brier_index"] for rel in R.BOTH for r in ix.get((rel, arm, pkt, sig, cov), {}).values()]
                cells.append("--" if not v else f"{st.fmean(v):.0f}".replace("-", "$-$"))
            lines.append(f"{name if i == 0 else ''} & {lab} & " + " & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    return "% generated by harness/paper.py; do not edit\n" + "\n".join(lines) + "\n"


def quotes_tex(qs):
    from .packet import ATTRIBUTION_NOTE, MIXED_NOTE
    out = ["% generated by harness/paper.py from the agents' messages and the prompt text; do not edit",
           f"\\newcommand{{\\PromptAttributionNote}}{{{tex_escape(ATTRIBUTION_NOTE)}}}",
           f"\\newcommand{{\\PromptMixedNote}}{{{tex_escape(MIXED_NOTE)}}}"]
    for qid, model, text, p, note in qs:
        name = "Quote" + qid.capitalize()
        out.append(f"\\newcommand{{\\{name}}}{{{tex_escape(text)}}}")
        out.append(f"\\newcommand{{\\{name}Model}}{{{MID[model][1]}}}")
        out.append(f"\\newcommand{{\\{name}P}}{{{p:.2f}}}")
    return "\n".join(out) + "\n"


